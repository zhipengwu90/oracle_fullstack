-- Stocks page watchlist: which symbols each logged-in user follows.
-- Prices are not stored; the API fetches them live from Yahoo Finance.
-- Idempotent: safe to re-run. Run it BEFORE deploying the code that uses it.
--
--   ( echo "SET ROLE wuz; SET search_path TO myapp_v1, public;"; cat sql/stocks_schema.sql ) | sudo -u postgres psql -d myapp -v ON_ERROR_STOP=1
--
--   (Piped, not -f: the postgres user can't read files under /home/ubuntu.
--   "public" is where Django's auth_user lives.)
--
-- auth_user lives in "public" and is found through the search_path
-- fallback, same as Django itself finds it.

CREATE TABLE IF NOT EXISTS stock_watch (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
    symbol      VARCHAR(20) NOT NULL,                                  -- Yahoo ticker: SHOP.TO, AAPL
    market      VARCHAR(2) NOT NULL CHECK (market IN ('CA', 'US')),
    asset_type  VARCHAR(10) NOT NULL CHECK (asset_type IN ('stock', 'etf')),
    name        VARCHAR(200),
    position    INTEGER NOT NULL DEFAULT 0,                            -- the user's own order (drag to reorder)
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, symbol)
);

-- Added after the table first shipped; a no-op on fresh installs.
ALTER TABLE stock_watch ADD COLUMN IF NOT EXISTS position INTEGER NOT NULL DEFAULT 0;
